package dev.krtirtho

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import java.io.File

abstract class GenerateVlcLoaderTask : DefaultTask() {

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val objectName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init {
        group = "build"
        description = "Generates the native VLC binary initialization loader script."
    }

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val objName = objectName.get()

        // Remove all previously generated files to avoid stale duplicates
        outputDirectory.asFile.get().deleteRecursively()

        // Convert package format "com.foo.bar" into path format "com/foo/bar"
        val packagePath = pkg.replace('.', '/')
        val outputFile = File(outputDirectory.asFile.get(), "$packagePath/$objName.kt")

        outputFile.parentFile.mkdirs()

        val sourceCode = $$"""
            /*
             * Copyright (C) 2026 Kingkor Roy Tirtho and Spotube Contributors
             * This code is auto-generated by vlcj-bundler Gradle Plugin. Do not modify.
             */

            package $$pkg

            import com.sun.jna.NativeLibrary
            import uk.co.caprica.vlcj.binding.support.runtime.RuntimeUtil
            import java.io.File

            object $$objName {
                fun getVerifiedPath(): String {
                    val os = System.getProperty("os.name").lowercase()
                    val arch = System.getProperty("os.arch").lowercase()

                    val osDir = when {
                        os.contains("win") -> "win-x64"
                        os.contains("mac") -> "macos-universal"
                        else -> "linux-x64"
                    }

                    val appResourcesDir = System.getProperty("compose.application.resources.dir")
                    var vlcPath = File(appResourcesDir ?: "", osDir)

                    if (appResourcesDir == null || !vlcPath.exists()) {
                        val projectRoot = File(System.getProperty("user.dir"))
                        val possibleDevPaths = listOf(
                            File(projectRoot, "build/vlc-natives/$osDir"),            // If user.dir is /composeApp
                            File(projectRoot, "composeApp/build/vlc-natives/$osDir"), // If user.dir is root
                            File(projectRoot, "vlc-natives/$osDir"),                  // Legacy root fallback
                            File(projectRoot, "composeApp/vlc-natives/$osDir")         // Legacy module fallback
                        )
                        vlcPath = possibleDevPaths.firstOrNull { it.exists() }
                            ?: throw IllegalStateException("VLC binaries missing globally.")
                    }

                    val absolutePath = vlcPath.absolutePath
                    
                    if (os.contains("mac")) {
                        val pluginsPath = "$absolutePath/plugins"
                        try {
                            // Use JNA to invoke the native C standard library 'setenv' function directly.
                            // This seamlessly updates the process environment variables without violating JVM encapsulation.
                            val libc = NativeLibrary.getInstance("c")
                            libc.getFunction("setenv").invokeInt(arrayOf<Any>("VLC_PLUGIN_PATH", pluginsPath, 1))
                        } catch (t: Throwable) {
                            // Fallback telemetry catch block if system linkage fails
                        }
                    }

                    // Inform JNA precisely where the dynamic linkers should target
                    NativeLibrary.addSearchPath(
                        RuntimeUtil.getLibVlcLibraryName(), 
                        if (os.contains("mac")) "$absolutePath/lib" else absolutePath,
                    )

                    System.setProperty("VLC_PLUGIN_PATH", "$absolutePath${File.separator}plugins")
                    if (os.contains("win")) {
                        System.setProperty("VLC_FORCE_PLUGIN_CACHE", "0")
                    }

                    return absolutePath
                }
            }
        """.trimIndent()

        outputFile.writeText(sourceCode)
    }
}